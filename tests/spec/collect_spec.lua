local H = require("helpers")

describe("collect (real repositories)", function()
  local dir
  before_each(function()
    require("git.config").setup({})
    dir = H.repo()
  end)
  after_each(function()
    H.rm(dir)
  end)

  it("handles an unborn branch", function()
    H.write(dir, "a.txt", "a")
    local s = H.collect(dir)
    eq(true, s.branch.unborn)
    eq("main", s.branch.head)
    eq({ "a.txt" }, H.paths(s, "untracked"))
    eq({}, s.graph)
  end)

  it("buckets staged, unstaged and untracked files with counts", function()
    H.write(dir, "keep.txt", { "1", "2", "3" })
    H.write(dir, "gone.txt", "x")
    H.commit(dir, "init")
    H.write(dir, "keep.txt", { "1", "two", "3", "4" })
    H.git(dir, { "add", "keep.txt" })
    H.write(dir, "keep.txt", { "1", "two", "3", "4", "5" })
    vim.fn.delete(dir .. "/gone.txt")
    H.write(dir, "my file ünï.txt", "new")
    local s = H.collect(dir)
    eq({ "keep.txt" }, H.paths(s, "staged"))
    eq(2, s.files.staged[1].added)
    eq(1, s.files.staged[1].deleted)
    table.sort(s.files.unstaged, function(a, b)
      return a.path < b.path
    end)
    eq({ "gone.txt", "keep.txt" }, H.paths(s, "unstaged"))
    eq("D", s.files.unstaged[1].code)
    eq(1, s.files.unstaged[2].added)
    eq({ "my file ünï.txt" }, H.paths(s, "untracked"))
  end)

  it("reports renames with their original path and binary files", function()
    H.write(dir, "old.txt", { "line 1", "line 2", "line 3", "line 4" })
    H.write(dir, "bin.dat", "\0\1\2\3")
    H.commit(dir, "init")
    H.git(dir, { "mv", "old.txt", "new.txt" })
    H.write(dir, "bin.dat", "\0\1\2\4\5")
    H.git(dir, { "add", "bin.dat" })
    local s = H.collect(dir)
    local by = {}
    for _, f in ipairs(s.files.staged) do
      by[f.path] = f
    end
    eq("old.txt", by["new.txt"].orig)
    eq("R", by["new.txt"].code)
    eq(true, by["bin.dat"].binary)
  end)

  it("reports conflicts and the merge in progress", function()
    H.write(dir, "f.txt", "base")
    H.commit(dir, "base")
    H.git(dir, { "checkout", "--quiet", "-b", "other" })
    H.write(dir, "f.txt", "other")
    H.commit(dir, "other")
    H.git(dir, { "checkout", "--quiet", "main" })
    H.write(dir, "f.txt", "main")
    H.commit(dir, "main")
    H.git(dir, { "merge", "other" }, true)
    local s = H.collect(dir)
    eq({ "f.txt" }, H.paths(s, "conflicted"))
    eq("UU", s.files.conflicted[1].code)
    eq("merge", s.operation)
  end)

  it("lists stashes, tags, the graph and detached HEAD", function()
    H.write(dir, "a", "1")
    H.commit(dir, "one")
    H.git(dir, { "tag", "v1.0" })
    H.write(dir, "a", "2")
    H.commit(dir, "two")
    H.write(dir, "a", "3")
    H.git(dir, { "stash", "push", "--quiet", "-m", "wip" })
    local s = H.collect(dir)
    eq(1, #s.stashes)
    eq("stash@{0}", s.stashes[1].ref)
    matches("wip", s.stashes[1].subject)
    eq(nil, s.tags.at_head)
    matches("^v1%.0%-1%-g", s.tags.nearest)
    eq(2, #s.graph)
    eq("two", s.graph[1].subject)
    -- no remote at all: every commit counts as unpushed
    eq(true, s.unpushed[s.graph[1].hash])

    H.git(dir, { "checkout", "--quiet", "v1.0" })
    s = H.collect(dir)
    eq(true, s.branch.detached)
    eq("v1.0", s.tags.at_head)
    eq({ "v1.0" }, s.tags.local_at_head)
  end)

  it("tracks ahead/behind, remote commits and unpushed tags against an upstream", function()
    local remote = H.repo()
    H.write(remote, "r", "1")
    H.commit(remote, "r1")
    H.git(dir, { "remote", "add", "origin", remote })
    H.git(dir, { "fetch", "--quiet", "origin" })
    H.git(dir, { "checkout", "--quiet", "-b", "main", "--track", "origin/main" })
    H.write(remote, "r", "2")
    H.commit(remote, "r2 upstream change")
    H.git(dir, { "fetch", "--quiet", "origin" })
    H.write(dir, "l", "1")
    H.commit(dir, "local change")
    H.git(dir, { "tag", "local-tag" })

    require("git.config").setup({ tags = { check_remote = true } })
    local s = H.collect(dir)
    eq("origin/main", s.branch.upstream)
    eq(1, s.branch.ahead)
    eq(1, s.branch.behind)
    eq("origin", s.remote)
    eq("r2 upstream change", s.remote_commits[1].subject)
    eq(true, s.unpushed[s.graph[1].hash])

    -- the remote tag list is fetched on demand and cached
    local collect = require("git.collect")
    eq(true, collect.resolve_unpushed_tags(s))
    local fetched = H.await(function(done)
      collect.fetch_remote_tags(s.repo, "origin", done)
    end)
    eq(true, fetched)
    eq(false, collect.resolve_unpushed_tags(s))
    eq({ "local-tag" }, s.tags.unpushed)
    H.rm(remote)
  end)

  it("reports a gone upstream", function()
    local remote = H.repo()
    H.write(remote, "r", "1")
    H.commit(remote, "r1")
    H.git(remote, { "branch", "feature" })
    H.git(dir, { "remote", "add", "origin", remote })
    H.git(dir, { "fetch", "--quiet", "origin" })
    H.git(dir, { "checkout", "--quiet", "-b", "feature", "--track", "origin/feature" })
    H.git(remote, { "branch", "-D", "feature" })
    H.git(dir, { "fetch", "--quiet", "--prune", "origin" })
    local s = H.collect(dir)
    eq(true, s.branch.gone)
    H.rm(remote)
  end)

  it("returns file diffs for every section", function()
    H.write(dir, "a.txt", { "one" })
    H.commit(dir, "init")
    H.write(dir, "a.txt", { "two" })
    H.write(dir, "u.txt", { "new" })
    local s = H.collect(dir)
    local collect = require("git.collect")
    local lines = H.await(function(done)
      collect.file_diff(s.repo, s.files.unstaged[1], done)
    end)
    ok(vim.tbl_contains(lines, "+two"))
    ok(vim.tbl_contains(lines, "-one"))
    local ulines = H.await(function(done)
      collect.file_diff(s.repo, s.files.untracked[1], done)
    end)
    ok(ulines and vim.tbl_contains(ulines, "+new"), vim.inspect(ulines))
  end)

  it("fails cleanly outside a repository", function()
    local plain = vim.fs.normalize(vim.fn.tempname())
    vim.fn.mkdir(plain, "p")
    local repo, err = H.await(function(done)
      require("git.repo").find(plain, done)
    end)
    eq(nil, repo)
    matches("Not a git repository", err)
    H.rm(plain)
  end)
end)
