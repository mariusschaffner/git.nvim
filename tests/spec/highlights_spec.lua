local highlights = require("git.highlights")

describe("highlights", function()
  it("never defines italic groups and keeps user overrides", function()
    vim.api.nvim_set_hl(0, "Comment", { fg = "#00ff00", italic = true })
    vim.api.nvim_set_hl(0, "GitStatusFile", { fg = "#123456", italic = true })
    highlights.setup()
    local dim = vim.api.nvim_get_hl(0, { name = "GitStatusDim" })
    eq(0x00ff00, dim.fg)
    eq(nil, dim.italic)
    eq(true, vim.api.nvim_get_hl(0, { name = "GitStatusFile" }).italic)
    eq(0x808080, vim.api.nvim_get_hl(0, { name = "GitStatusBorder" }).fg)
    ok(vim.api.nvim_get_hl(0, { name = "GitStatusUnpushedLine" }).bg)
    eq(nil, vim.api.nvim_get_hl(0, { name = "GitStatusUnpushedLine" }).fg)

    -- colorscheme changes are picked up for our own groups
    vim.api.nvim_set_hl(0, "Comment", { fg = "#0000ff", italic = true })
    highlights.setup()
    eq(0x0000ff, vim.api.nvim_get_hl(0, { name = "GitStatusDim" }).fg)
  end)

  it("drops copied backgrounds and blends the unpushed row over the window background", function()
    vim.api.nvim_set_hl(0, "Normal", { fg = "#dddddd", bg = "#101010" })
    vim.api.nvim_set_hl(0, "NormalFloat", { bg = "#000000" })
    vim.api.nvim_set_hl(0, "GitStatusSubject", {})
    highlights.setup()
    local subject = vim.api.nvim_get_hl(0, { name = "GitStatusSubject" })
    eq(0xdddddd, subject.fg)
    eq(nil, subject.bg)
    -- floats (the default kind) blend over NormalFloat
    eq("#0a1e0d", highlights.blend(0x3fb950, 0.16))
    eq("#808080", highlights.blend(0xffffff, 0.5))
  end)
end)
